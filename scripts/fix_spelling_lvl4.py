    for idx, w in enumerate(gen_spelling_lvl4.WORDS_LVL4):
        f.write(f"  # {idx + 1}. {w['word']}\n")
        f.write("  {\n")
        f.write(f"    \"word\": {repr(w['word'])}, \"wrong\": {repr(w['wrong'])}, \"rule\": {repr(w['rule'])}, \"def\": {repr(w['def'])}, \"pos\": {repr(w['pos'])},\n")
