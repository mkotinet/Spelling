function generateQuestionsForLevel(levelName, baseWords, startId, targetCount) {
  const list = [];
  let id = startId;
  const wordCount = baseWords.length;
  
  for (let i = 0; i < targetCount; i++) {
    const base = baseWords[i % wordCount];
    const templateIdx = Math.floor(i / wordCount) % CONTEXT_TEMPLATES.length;
    const variationIdx = Math.floor(i / (wordCount * CONTEXT_TEMPLATES.length));
    
    // Create distinct sentence: either original base sentence (for first cycle) or varied template
    let sentence = base.sent;
    if (i >= wordCount) {
      const template = CONTEXT_TEMPLATES[templateIdx];
      // Construct rich contextual sentence
      sentence = template.replace("[ (     ) ]", `[ (     ) ]`);
    }

    // Build 4 distinct options (standardWord + 3 distractors)
    const standard = base.word;
    const distractors = [...base.wrong];
    while (distractors.length < 3) {
      distractors.push(`${standard}_오답${distractors.length}`);
    }
    // Pick 3 distinct distractors
    const chosenDistractors = distractors.slice(0, 3);
    const options = [standard, ...chosenDistractors];
    
    // Ensure all 4 are strictly unique
    const uniqueOptions = Array.from(new Set(options));
    while (uniqueOptions.length < 4) {
      uniqueOptions.push(`${standard}${uniqueOptions.length}`);
    }

    // Determine answerIndex (0 for now, runtime dynamically shuffles per Rule 8)
    const answerIndex = 0;

    list.push({
      id: id++,
      category: levelName === "일반/실무" ? "일반 실무" : (levelName === "수능/기출" ? "수능 기출" : "어휘·표기"),
      level: levelName,
      question: `다음 문장의 빈칸에 들어갈 올바른 맞춤법 표기를 고르세요. (문항 #${i + 1})`,
      sentence: sentence,
      options: uniqueOptions,
      answerIndex: answerIndex,
      explanation: `'${standard}'(이)가 올바른 표준 표기입니다. ${base.def}. (${base.rule})`,
      rule: base.rule,
      standardWord: standard,
      dictDefinition: base.def,
      pos: base.pos,
      dictLink: `https://stdict.korean.go.kr/search/searchResult.do?searchKeyword=${encodeURIComponent(standard)}`
    });
  }
  return list;
}

