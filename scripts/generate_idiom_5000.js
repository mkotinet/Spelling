function generateIdiomsForLevel(levelName, baseList, startId, targetCount) {
  const list = [];
  let id = startId;
  const count = baseList.length;

  for (let i = 0; i < targetCount; i++) {
    const base = baseList[i % count];
    const templateIdx = Math.floor(i / count) % CONTEXT_TEMPLATES_IDIOM.length;
    
    let sentence = base.sent;
    if (i >= count) {
      sentence = CONTEXT_TEMPLATES_IDIOM[templateIdx];
    }

    const standard = base.word;
    const distractors = [...base.wrong];
    while (distractors.length < 3) {
      distractors.push(`${standard}_오답${distractors.length}`);
    }
    const options = [standard, ...distractors.slice(0, 3)];
    const uniqueOptions = Array.from(new Set(options));
    while (uniqueOptions.length < 4) {
      uniqueOptions.push(`${standard}${uniqueOptions.length}`);
    }

    list.push({
      id: id++,
      category: base.category,
      level: levelName,
      question: `다음 문장의 빈칸에 들어갈 알맞은 속담 또는 관용구를 고르세요. (문항 #${i + 1})`,
      sentence: sentence,
      options: uniqueOptions,
      answerIndex: 0,
      idiomWord: standard,
      meaning: base.def,
      explanation: `'${standard}'은(는) "${base.def}"을(를) 뜻하는 표현입니다. 문맥상 가장 자연스럽고 올바른 어휘입니다.`,
      exampleSentence: base.sent,
      dictLink: `https://stdict.korean.go.kr/search/searchResult.do?searchKeyword=${encodeURIComponent(standard.split(" ")[0])}`
    });
  }
  return list;
}

